import test from 'node:test';
import assert from 'node:assert/strict';
import {abrirBanco} from '../src/banco.js';
import {ContextoApp} from '../src/contexto-app.js';
import {Desktop,VERSAO_TERMOS} from '../src/desktop.js';
import {LumePessoal} from '../src/pessoal/servico.js';
import {ExperienciaLume} from '../src/experiencia-lume.js';
import {pessoalPost} from '../src/pessoal/http.js';
test('preparação e acompanhamento usam autoridade existente sem enviar ou aprovar',async t=>{
 const db=abrirBanco(':memory:');new ContextoApp(db);const desktop=new Desktop(db);
 desktop.aceitar({nome:'Ensaio fictício',aceito:true,versao:VERSAO_TERMOS});
 const forbidden=()=>{throw Error('Envio externo proibido neste teste');};
 const service=new LumePessoal(db,{desktop,chatgpt:{estado:async()=>({}),encerrar(){},responder:forbidden},conexao:{estado:()=>({estado:'desconectada'}),enviarTexto:forbidden},fetchImpl:forbidden});
 t.after(async()=>{await service.encerrar();db.close();});
 const id='550000000001@s.whatsapp.net',texto='Confira o catálogo sintético.';
 db.prepare('INSERT INTO conversas_app VALUES(?,?)').run(id,'Contato fictício');
 const event=Number(db.prepare("INSERT INTO eventos(conversa_id,origem_id,direcao,autor_id,tipo,bruto,texto,recebido_em,dia_local,permissao) VALUES(?,?,'entrada',?,'texto','{}',?,'2026-10-26T12:00:00Z','2026-10-26','dirigida')").run(id,'fixture',id,texto).lastInsertRowid);
 const action=service.contexto.registrarDemanda({eventoId:event,resumo:'Conferir catálogo',trecho:texto,tipo:'pendencia'}).acaoId;
 const view=new ExperienciaLume(db,{acoes:service.contexto.acoes,produto:desktop,pessoal:service});
 const permissions=()=>view.listar().itens[0].acoes.map(a=>a.tipo);
 assert.equal(permissions().includes('preparar'),false);
 await assert.rejects(()=>pessoalPost(service,'/api/v3/pessoal/acompanhamento',{acaoId:action,confirmar:true}));
 await service.configurar({enabled:true});
 service.politica.configurar({conversaId:id,categoria:'lead',modo:'rascunhar',remoto:true});
 db.prepare('INSERT INTO desktop_ia_conversas VALUES(?,1,?)').run(id,new Date().toISOString());
 assert.ok(permissions().includes('preparar'));assert.ok(permissions().includes('acompanhar'));
 await assert.rejects(()=>pessoalPost(service,'/api/v3/pessoal/acompanhamento',{acaoId:action}));
 const following=await pessoalPost(service,'/api/v3/pessoal/acompanhamento',{acaoId:action,confirmar:true});assert.equal(following.acaoId,action);
 assert.equal(permissions().includes('acompanhar'),false);
 const draft=await pessoalPost(service,'/api/v3/pessoal/mensagem/preparar',{conversaId:id,baloes:['Sou Lume, assistente. Vou conferir o catálogo sintético.'],motivo:'Resposta escrita para o ensaio local.'});
 assert.equal(draft.estado,'pendente');assert.equal(db.prepare('SELECT COUNT(*) n FROM saidas').get().n,0);
 service.politica.pausar(id);assert.equal(permissions().includes('preparar'),false);
  assert.equal(db.prepare('SELECT estado FROM pessoal_propostas WHERE id=?').get(draft.id).estado,'cancelada');
  service.politica.controlar({conversaId:id,acao:'excluir'});
  await assert.rejects(()=>pessoalPost(service,'/api/v3/pessoal/acompanhamento',{acaoId:action,confirmar:true}));
  assert.equal(view.listar().itens.length,0);
 await assert.rejects(()=>pessoalPost(service,'/api/v3/pessoal/acompanhamento',{acaoId:action,confirmar:true,enviar:true}));
});
