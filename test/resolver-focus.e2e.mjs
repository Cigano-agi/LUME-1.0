// Foco do Resolver no renderer/API reais, SQLite somente em memória.
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
import {abrirBanco} from '../src/banco.js';
import {criarServidor} from '../src/painel/servidor.js';
import {perfilBeta05} from './fixtures/beta05-profile.js';
import {AcoesLume} from '../src/acoes-lume.js';
import {ExecucoesLume} from '../src/execucao/servico.js';

const output=process.argv[2]||process.env.LUME_03A33_FOCUS_OUTPUT||'docs/beta-06/evidencias-ui/03A33-2026-09-27/focus';
mkdirSync(output,{recursive:true});
const db=abrirBanco(':memory:');
const {contexto,desktop,fontes}=perfilBeta05(db,{agora:new Date('2026-09-27T14:00:00Z')});
const actions=new AcoesLume(db);
actions.autorizar({conversa:'demo-ana',permitida:true});
actions.autorizar({conversa:'demo-marcos',permitida:true});
actions.registrar({eventoId:fontes.ana.id,candidatas:[{fonte:'E'+fontes.ana.id,tipo:'compromisso',resumo:'Preparar a reunião de revisão com Ana',trecho:'Nossa reunião de revisão ficou para 24/09 às 10h.',prazo_citado:'24/09 às 10h'}]});
const confirmed=actions.listar({estado:'sugerido'}).find(item=>item.evento_id===fontes.ana.id);
actions.revisar({id:confirmed.id,acao:'confirmar'});
actions.registrar({eventoId:fontes.marcos.id,candidatas:[{fonte:'E'+fontes.marcos.id,tipo:'compromisso',resumo:'Conferir escopo com Marcos',trecho:'Quero conversar sobre o escopo antes de decidir.',prazo_citado:''}]});
const resolverAction=actions.listar({estado:'sugerido'}).find(item=>item.evento_id===fontes.marcos.id);
actions.revisar({id:resolverAction.id,acao:'confirmar'});
const execucoes=new ExecucoesLume(db);
const contextoId=execucoes.preparar({acao_id:confirmed.id}).contexto.id;
const execucaoId=execucoes.iniciar({contexto_id:contextoId,assistente:'claude',confirmar:true,chave_idempotencia:'03A33-focus-start'}).execucao.id;
execucoes.registrar('inicio',{execucao_id:execucaoId,chave_idempotencia:'03A33-focus-begin'});
desktop.configurarGuia({dispensado:true});
const server=criarServidor(db,{contexto,desktop:true,conexao:{estado:()=>({estado:'desconectada',qr:null}),parar:async()=>{},iniciar:async()=>{throw Error('Conexão vedada');}}});
const evidence={synthetic:true,cases:[],errors:[],external:[]};
let browser;
try{
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const origin=`http://127.0.0.1:${server.address().port}`;
  browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:390,height:900},reducedMotion:'reduce'});
  page.on('pageerror',e=>evidence.errors.push(e.message));
  page.on('request',r=>{if(!r.url().startsWith(origin))evidence.external.push(r.url());});
  await page.route(/^(?!http:\/\/127\.0\.0\.1:).*$/u,route=>route.abort());
  await page.goto(origin+'/app');
  await page.locator('#luminus-body .resolver-open').first().waitFor();
  await page.evaluate(()=>{
    window.focusTrace=[];
    const item=(type)=>window.focusTrace.push({type,active:document.activeElement?.tagName,cls:document.activeElement?.className?.toString().slice(0,70),open:document.querySelector('#resolver-dialog').open});
    const open=window.abrirResolverLume;
    window.abrirResolverLume=(...args)=>{item('open-entry');return open(...args);};
    document.addEventListener('focusin',()=>item('focusin'));
    document.querySelector('#resolver-dialog').addEventListener('cancel',()=>item('cancel'));
    document.querySelector('#resolver-dialog').addEventListener('close',()=>item('close'));
  });
  const run=async(theme,width,method)=>{
    await page.setViewportSize({width,height:900});
    const trigger=page.locator('#luminus-body .resolver-open').first();
    await trigger.focus();
    const handle=await trigger.elementHandle();
    await page.keyboard.press('Enter');
    await page.locator('#resolver-dialog[open]').waitFor();
    await page.locator('#resolver-consent').waitFor();
    await page.screenshot({path:`${output}/resolver-${theme}-${width}-${method}.png`});
    if(method==='escape')await page.keyboard.press('Escape');
    else await page.getByRole('button',{name:'Fechar Resolver com'}).click();
    await page.locator('#resolver-dialog[open]').waitFor({state:'hidden'});
    await page.waitForTimeout(100);
    const state=await handle.evaluate(n=>({connected:n.isConnected,focused:document.activeElement===n,activeTag:document.activeElement?.tagName,trace:window.focusTrace.splice(0)}));
    evidence.cases.push({theme,width,method,...state});
    assert.equal(state.focused,true,`${method} must restore source focus: ${JSON.stringify(state)}`);
    await page.screenshot({path:`${output}/today-${theme}-${width}-${method}-returned.png`});
  };
  await run('light',390,'escape');
  await run('light',390,'button');
  await page.locator('nav [data-view=settings]').click();
  await page.locator('#settings-choice-data').click();
  await page.locator('#theme-mode').selectOption('dark');
  await page.locator('nav [data-view=today]').click();
  await run('dark',1440,'escape');
  await run('dark',1440,'button');
  const history=page.locator('#acoes06-list').getByRole('button',{name:'Ver andamento'}).first();
  await history.focus();const historyHandle=await history.elementHandle();
  await page.keyboard.press('Enter');await page.locator('#resolver-dialog[open]').waitFor();
  await page.keyboard.press('Escape');await page.locator('#resolver-dialog[open]').waitFor({state:'hidden'});
  await page.waitForTimeout(100);
  const historyFocused=await historyHandle.evaluate(n=>document.activeElement===n);
  assert.equal(historyFocused,true,'Ver andamento restores its own origin');
  evidence.cases.push({theme:'dark',width:1440,method:'history-escape',focused:historyFocused});
  // Keep the first API read pending: Escape must still restore the opener.
  let releasePending;
  const pending=new Promise(resolve=>{releasePending=resolve;});
  await page.route(url=>url.pathname==='/api/v3/execucoes',route=>pending.then(()=>route.continue()));
  const pendingTrigger=page.locator('#luminus-body .resolver-open').first();
  await pendingTrigger.focus();
  const pendingHandle=await pendingTrigger.elementHandle();
  await page.keyboard.press('Enter');
  await page.locator('#resolver-dialog[open]').waitFor();
  const disabledWhilePending=await pendingTrigger.isDisabled();
  await page.keyboard.press('Escape');
  await page.locator('#resolver-dialog[open]').waitFor({state:'hidden'});
  await page.waitForTimeout(100);
  const pendingState=await pendingHandle.evaluate(n=>({connected:n.isConnected,focused:document.activeElement===n,disabled:n.disabled,active:document.activeElement?.tagName}));
  releasePending();await page.unrouteAll({behavior:'ignoreErrors'});
  evidence.cases.push({theme:'dark',width:1440,method:'escape-pending-api',disabledWhilePending,...pendingState});
  assert.equal(pendingState.focused,true,`pending request Escape must restore focus: ${JSON.stringify(pendingState)}`);
  // A close event queued for the prior session must not clear a quick reopening.
  const trigger=page.locator('#luminus-body .resolver-open').first();
  await trigger.focus();await page.keyboard.press('Enter');
  await page.locator('#resolver-consent').waitFor();
  await page.evaluate(()=>{document.querySelector('#resolver-dialog').close();document.querySelector('#luminus-body .resolver-open').click();});
  await page.locator('#resolver-consent').waitFor();
  await page.waitForTimeout(100);
  assert.equal(await page.locator('#resolver-dialog[open]').count(),1,'quick reopening remains open');
  assert.equal(await page.locator('#resolver-consent').count(),1,'quick reopening retains content');
  evidence.cases.push({theme:'dark',width:1440,method:'quick-reopen',open:true,content:true});
  await page.keyboard.press('Escape');await page.locator('#resolver-dialog[open]').waitFor({state:'hidden'});
  // An obsolete opener must not throw or shift focus to unrelated controls.
  await trigger.focus();await page.keyboard.press('Enter');await page.locator('#resolver-consent').waitFor();
  const detached=await trigger.elementHandle();await detached.evaluate(n=>n.remove());
  await page.keyboard.press('Escape');await page.locator('#resolver-dialog[open]').waitFor({state:'hidden'});
  await page.waitForTimeout(100);
  const invalid=await detached.evaluate(n=>({connected:n.isConnected,active:document.activeElement?.tagName}));
  assert.equal(invalid.connected,false);
  evidence.cases.push({theme:'dark',width:1440,method:'detached-origin',...invalid});
  const disabledOrigin=page.locator('#acoes06-list .resolver-open').first();
  await disabledOrigin.focus();await page.keyboard.press('Enter');await page.locator('#resolver-dialog[open]').waitFor();
  await disabledOrigin.evaluate(n=>{n.disabled=true;});
  await page.keyboard.press('Escape');await page.locator('#resolver-dialog[open]').waitFor({state:'hidden'});
  await page.waitForTimeout(100);
  const disabledState=await disabledOrigin.evaluate(n=>({disabled:n.disabled,focused:document.activeElement===n}));
  assert.equal(disabledState.focused,false,'disabled origin is not refocused');
  evidence.cases.push({theme:'dark',width:1440,method:'disabled-origin',...disabledState});
  await disabledOrigin.evaluate(n=>{n.disabled=false;});
  // The settings link is deliberate navigation; closing Resolver must not reclaim focus.
  const card=page.locator('#acoes06-list .resolver-open').first();
  await card.click();await page.locator('#resolver-consent').waitFor();
  await page.locator('#resolver-consent').check();
  await page.getByRole('button',{name:'Autorizar contexto →'}).click();
  await page.locator('.resolver-state').filter({hasText:'Aguardando o assistente'}).waitFor();
  await page.getByRole('button',{name:'Conferir conexão'}).click();
  await page.locator('#settings:not([hidden])').waitFor();
  await page.waitForTimeout(100);
  const navigation=await card.evaluate(n=>({dialogClosed:!document.querySelector('#resolver-dialog').open,settingsVisible:!document.querySelector('#settings').hidden,focusStolen:document.activeElement===n,active:document.activeElement?.tagName}));
  assert.equal(navigation.focusStolen,false);
  evidence.cases.push({theme:'dark',width:1440,method:'settings-navigation',...navigation});
  // Clearing visible data closes the dialog without focusing a soon-invalid source.
  await page.locator('nav [data-view=today]').click();
  await page.locator('#acoes06-list .resolver-open').first().click();
  await page.locator('#resolver-dialog[open]').waitFor();
  await page.evaluate(()=>window.limparDadosVisiveis());
  await page.locator('#resolver-dialog[open]').waitFor({state:'hidden'});
  await page.waitForTimeout(100);
  evidence.cases.push({theme:'dark',width:1440,method:'clear-visible-data',value:await page.evaluate(()=>({closed:!document.querySelector('#resolver-dialog').open,active:document.activeElement?.tagName,actions:document.querySelectorAll('#acoes06-list .resolver-open').length}))});
  assert.deepEqual(evidence.errors,[]);
  assert.deepEqual(evidence.external,[]);
  console.log(JSON.stringify({ok:true,cases:evidence.cases.length,errors:evidence.errors,external:evidence.external}));
}catch(error){evidence.failure={message:error.message,stack:error.stack};console.error(error);process.exitCode=1;}
finally{
  writeFileSync(`${output}/evidence.json`,JSON.stringify(evidence,null,2));
  if(browser)await browser.close();
  if(server.listening){server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}
  db.close();
}
